# 집합 기초

# ===========================================================
#  집합 (set): 여러 객체를 순서 없이 중복을 허용하지 않고 저장하는 변경 가능한 자료형
#  집합의 특징
#  1. ( mutable, 변경 가능 )
#  2. ( iterable, 반복 가능 )
#  3. ( sequence X, 인덱싱과 슬라이싱 블가 )
#  4. ( 중복 허용 안함 )
# ===========================================================

# 집합 생성
# a = {}   <- 딕셔너리
a = set()
print(type(a))

a = {3, 3, 2, 1, 2}
print(a)

# ===========================================================
# 1. 집합은 mutable하다. (변경 가능)
# ===========================================================

a.update({3, 4})
print(a)

a.pop()  # index도 없고 key도 없으므로 지정하여 삭제 불가. 랜덤으로 사라짐
print(a)

# ===========================================================
# 2. 집합은 iterable하다. (반복 가능)
# ===========================================================

# 집합 순회
for x in a:
    print(x)

# ===========================================================
# 3. 집합은 sequence 객체가 아니다. (인덱싱, 슬라이싱 불가)
# ===========================================================

# a[100]     # __setitem__

# ===========================================================
# 4. 집합은 중복을 허용하지 않는다.
# ===========================================================

s = {10, 10, 20, 20, 30}
print(s)

# ===========================================================
#  파이썬 내장 함수
# ===========================================================

print(len(s))
print(sum(s))
print(min(s), max(s))
print(sorted(s))

# 집합 합치기
s2 = {40, 50}
# print(s + s2)
print(s.union(s2))

